export const QUIZ_PASS = 8; // минимум правильных из 10

export function publicQuiz() {
  return QUIZ.map(({ q, options }) => ({ q, options }));
}

export function scoreQuiz(answers: number[]): { score: number; total: number; passed: boolean } {
  const total = QUIZ.length;
  let score = 0;
  for (let i = 0; i < total; i++) {
    if (answers[i] === QUIZ[i].correct) score++;
  }
  return { score, total, passed: score >= QUIZ_PASS };
}
